func startSelfPing() {
	appURL := os.Getenv("APP_URL")
	if appURL == "" {
		appURL = "https://ehubgo.onrender.com"
		log.Println("APP_URL not set, defaulting self-ping to", appURL)
	}

	ticker := time.NewTicker(5 * time.Minute)

	go func() {
		for range ticker.C {
			resp, err := http.Get(appURL + "/health")
			if err != nil {
				log.Println("self-ping failed:", err)
				continue
			}

			resp.Body.Close()
			log.Println("self-ping success:", resp.Status)
		}
	}()
}

func AuthMiddleware(authClient *auth.Client, dbConn *sql.DB) gin.HandlerFunc {
	return func(c *gin.Context) {
		authHeader := c.GetHeader("Authorization")

		if authHeader == "" {
			if os.Getenv("DEV_AUTH_BYPASS") == "true" && os.Getenv("GO_ENV") != "production" {
				c.Set("user_id", "test-user-id")
				c.Set("user_email", "dev@example.com")
				c.Set("user_roles", "executive_admin,admin,vendor,customer")
				c.Set("user_dob", "2000-01-01")
			}
			c.Next()
			return
		}

		tokenString := strings.TrimSpace(strings.Replace(authHeader, "Bearer", "", 1))
		token, err := authClient.VerifyIDToken(c.Request.Context(), tokenString)
		if err != nil {
			c.AbortWithStatusJSON(http.StatusUnauthorized, gin.H{"error": "Invalid or expired token"})
			return
		}

		c.Set("user_id", token.UID)

		// Fetch roles and DOB from DB
		var roles sql.NullString
		var dob sql.NullTime
		err = dbConn.QueryRowContext(c.Request.Context(), 
			"SELECT (SELECT string_agg(role::text, ',') FROM user_roles WHERE user_id = $1), date_of_birth FROM users WHERE id = $1", 
			token.UID).Scan(&roles, &dob)
		
		if err == nil {
			if roles.Valid && roles.String != "" {
				c.Set("user_roles", roles.String)
			} else {
				c.Set("user_roles", "user")
			}
			if dob.Valid {
				c.Set("user_dob", dob.Time.Format("2006-01-02"))
			}
		} else {
			c.Set("user_roles", "user") // default basic role
		}

		c.Next()
	}
}

// RequireAuth is a helper to ensure user is logged in for specific routes
func RequireAuth() gin.HandlerFunc {
	return func(c *gin.Context) {
		_, exists := c.Get("user_id")
		if !exists {
			c.AbortWithStatusJSON(http.StatusUnauthorized, gin.H{"error": "Authentication required"})
			return
		}
		c.Next()
	}
}

